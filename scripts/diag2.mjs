import { chromium } from 'playwright';
import { readFileSync } from 'node:fs';
const browser = await chromium.launch();
const page = await browser.newPage();
page.on('pageerror', (e) => console.log('PAGEERROR', e.message.slice(0,300)));
page.on('console', (m) => { if (m.type()==='error') console.log('CONSOLE', m.text().slice(0,300)); });
await page.goto('http://localhost:4181/', { waitUntil: 'networkidle' });
await page.getByRole('button', { name: 'Upload', exact: true }).click();
await page.setInputFiles('input[type=file]', '/tmp/e2e-import.mid');
await page.waitForTimeout(2500);
console.log('banners', await page.locator('.banner').allInnerTexts());
console.log('body head', (await page.locator('main').innerText()).slice(0, 300));
console.log('svg?', await page.locator('.score-canvas svg').count());
await browser.close();
